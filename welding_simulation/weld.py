# Step 2: Download the public GitHub repository archive.
# Extract only the welding_simulation directory into Google Drive.

import os
import requests
import zipfile
import io

destination = "/content/drive/MyDrive/welding_simulation"

os.makedirs(destination, exist_ok=True)

url = (
    "https://github.com/Afshinrommel/"
    "welding-telemetry-streaming/archive/refs/heads/main.zip"
)

response = requests.get(url, timeout=120)
response.raise_for_status()

prefix = "welding-telemetry-streaming-main/welding_simulation/"

with zipfile.ZipFile(io.BytesIO(response.content)) as archive:
    for item in archive.infolist():
        if item.filename.startswith(prefix) and not item.is_dir():
            relative_path = item.filename[len(prefix):]
            target = os.path.join(destination, relative_path)

            os.makedirs(os.path.dirname(target), exist_ok=True)

            with archive.open(item) as src, open(target, "wb") as dst:
                dst.write(src.read())

print("Project download and extraction completed.")
print("Destination:", destination)

# List all extracted files.
for root, dirs, files in os.walk(destination):
    for filename in files:
        print(os.path.relpath(os.path.join(root, filename), destination))

